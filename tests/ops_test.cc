struct SymInt {
  std::array<int64_t, 2> data;
};

struct TensorMetadata {
  ScalarType dtype;
  std::vector<SymInt> shape;
};

struct Node {
  Operator target;
  std::vector<TensorMetadata> args;
  TensorMetadata meta;
};

struct Graph {
  std::vector<Node> nodes;
};

void serialize(flatbuffers::FlatBufferBuilder &builder, const Graph &graph) {
  auto nodes = std::vector<flatbuffers::Offset<flatflow::Node>>();
  nodes.reserve(graph.nodes.size());

  for (const auto &node : graph.nodes) {
    auto args = std::vector<flatbuffers::Offset<flatflow::TensorMetadata>>();
    args.reserve(node.args.size());

    for (const auto &arg : node.args) {
      auto shape = std::vector<flatflow::SymInt>();
      shape.reserve(arg.shape.size());
      for (const auto &s : arg.shape) {
        shape.emplace_back(s.data);
      }
      args.emplace_back(CreateTensorMetadata(
          builder, arg.dtype, builder.CreateVectorOfStructs(shape)));
    }

    auto shape = std::vector<flatflow::SymInt>();
    shape.reserve(node.meta.shape.size());
    for (const auto &s : node.meta.shape) {
      shape.emplace_back(s.data);
    }
    const auto meta = CreateTensorMetadata(
        builder, node.meta.dtype, builder.CreateVectorOfStructs(shape));

    nodes.emplace_back(
        CreateNode(builder, node.target, builder.CreateVector(args), meta));
  }

  builder.Finish(CreateGraph(builder, builder.CreateVector(nodes)));
}

